CREATE TABLE test_requests (
    id BIGINT NOT NULL AUTO_INCREMENT,
    request_number VARCHAR(80) NOT NULL,
    request_date DATE NOT NULL,
    customer_name VARCHAR(200) NOT NULL,
    tax_code VARCHAR(40) NULL,
    contact_person VARCHAR(160) NULL,
    customer_address VARCHAR(500) NULL,
    customer_phone VARCHAR(30) NOT NULL,
    customer_email VARCHAR(200) NULL,
    sample_name VARCHAR(200) NOT NULL,
    lot_code VARCHAR(100) NULL,
    variety VARCHAR(120) NULL,
    origin VARCHAR(255) NULL,
    harvest_date DATE NULL,
    packing_date DATE NULL,
    sampling_mode VARCHAR(30) NOT NULL,
    purpose VARCHAR(500) NULL,
    expected_date DATE NULL,
    result_delivery_method VARCHAR(120) NULL,
    service_conditions TEXT NULL,
    delay_notice VARCHAR(120) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_test_requests_number (request_number),
    KEY idx_test_requests_date (request_date),
    CONSTRAINT fk_test_requests_created_by FOREIGN KEY (created_by_user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE test_request_items (
    id BIGINT NOT NULL AUTO_INCREMENT,
    test_request_id BIGINT NOT NULL,
    row_order INT NOT NULL,
    sample_name_or_id VARCHAR(200) NOT NULL,
    parameters_text TEXT NOT NULL,
    sample_matrix VARCHAR(120) NULL,
    test_method VARCHAR(200) NULL,
    PRIMARY KEY (id),
    KEY idx_test_request_items_request (test_request_id, row_order),
    CONSTRAINT fk_test_request_items_request FOREIGN KEY (test_request_id) REFERENCES test_requests(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sampling_plans (
    id BIGINT NOT NULL AUTO_INCREMENT,
    test_request_id BIGINT NOT NULL,
    form_number VARCHAR(80) NOT NULL,
    form_date DATE NOT NULL,
    representative VARCHAR(160) NULL,
    sample_collector VARCHAR(160) NOT NULL,
    collector_phone VARCHAR(30) NULL,
    sampling_start TIMESTAMP(6) NULL,
    sampling_end TIMESTAMP(6) NULL,
    sampling_location VARCHAR(500) NULL,
    growing_area VARCHAR(255) NULL,
    packing_facility VARCHAR(255) NULL,
    vehicle_number VARCHAR(80) NULL,
    trailer_number VARCHAR(80) NULL,
    container_number VARCHAR(80) NULL,
    scheme_notes TEXT NULL,
    transport_conditions TEXT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_sampling_plans_request (test_request_id),
    UNIQUE KEY uk_sampling_plans_number (form_number),
    CONSTRAINT fk_sampling_plans_request FOREIGN KEY (test_request_id) REFERENCES test_requests(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE field_sampling_forms (
    id BIGINT NOT NULL AUTO_INCREMENT,
    test_request_id BIGINT NOT NULL,
    form_number VARCHAR(80) NOT NULL,
    form_date DATE NOT NULL,
    representative VARCHAR(160) NULL,
    sample_collector VARCHAR(160) NOT NULL,
    collector_phone VARCHAR(30) NULL,
    sampling_start TIMESTAMP(6) NULL,
    sampling_end TIMESTAMP(6) NULL,
    sampling_location VARCHAR(500) NULL,
    growing_area VARCHAR(255) NULL,
    packing_facility VARCHAR(255) NULL,
    vehicle_number VARCHAR(80) NULL,
    trailer_number VARCHAR(80) NULL,
    container_number VARCHAR(80) NULL,
    sample_condition VARCHAR(120) NULL,
    storage_condition VARCHAR(120) NULL,
    sample_seal_number VARCHAR(80) NULL,
    seal_present BOOLEAN NOT NULL DEFAULT FALSE,
    sampling_method VARCHAR(255) NULL,
    sample_quantity VARCHAR(120) NULL,
    field_notes TEXT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_field_sampling_request (test_request_id),
    UNIQUE KEY uk_field_sampling_number (form_number),
    CONSTRAINT fk_field_sampling_request FOREIGN KEY (test_request_id) REFERENCES test_requests(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

